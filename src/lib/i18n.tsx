export type TKey = string;

type Ctx = {
  lang: Lang;
  dir: "ltr" | "rtl";
  t: (k: string) => string;
  setLang: (l: Lang) => void;
  toggle: () => void;
};

const LangContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("ayxa-lang");
    if (saved === "ar" || saved === "en") setLangState(saved);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("ayxa-lang", l);
  }, []);

  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const t = useCallback(
    (key: string) => {
      if (!key) return "";
      if (dict[key] && dict[key][lang]) {
        return dict[key][lang];
      }
      // Check case-insensitive match in dictionary
      const lowerKey = key.toLowerCase().trim();
      for (const dKey of Object.keys(dict)) {
        if (dKey.toLowerCase() === lowerKey || dict[dKey].en.toLowerCase() === lowerKey) {
          return dict[dKey][lang];
        }
      }
      return key;
    },
    [lang]
  );

  const value = useMemo<Ctx>(
    () => ({
      lang,
      dir,
      t,
      setLang,
      toggle: () => setLang(lang === "en" ? "ar" : "en"),
    }),
    [lang, dir, t, setLang]
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}
